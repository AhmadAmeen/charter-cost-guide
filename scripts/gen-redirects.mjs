#!/usr/bin/env node
/**
 * Generates public/_redirects from src/data/programs.ts.
 * For each APPROVED program with a url, writes one line:
 *   /go/{key} {url} 302
 * If subParam is set, appends it per the program's own tracking instructions
 * (the owner supplies the exact value).
 * Pending or paused programs produce no redirect and therefore no live link.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const programsPath = join(root, 'src', 'data', 'programs.ts');
const outPath = join(root, 'public', '_redirects');

const src = readFileSync(programsPath, 'utf8');

// Parse the simple object-literal entries in programs.ts.
// Matches: key: { name: '...', kind: '...', status: '...', url: '...', subParam: '...', cta: '...' },
const entryRe = /(\w+):\s*\{\s*name:\s*'([^']*)',\s*kind:\s*'(\w+)',\s*status:\s*'(\w+)',\s*url:\s*'([^']*)',\s*subParam:\s*'([^']*)',\s*cta:\s*'([^']*)'\s*\}/g;

const lines = [];
let m;
while ((m = entryRe.exec(src)) !== null) {
  const [, key, , , status, url, subParam] = m;
  if (status === 'approved' && url) {
    let dest = url;
    if (subParam) {
      const sep = dest.includes('?') ? '&' : '?';
      dest = `${dest}${sep}${subParam}`;
    }
    lines.push(`/go/${key} ${dest} 302`);
  }
}

const header = '# Generated by scripts/gen-redirects.mjs — do not edit by hand.\n';
writeFileSync(outPath, header + (lines.length ? lines.join('\n') + '\n' : ''));
console.log(`gen-redirects: wrote ${lines.length} redirect(s) to public/_redirects`);
